"""Generate the shared CSS/Dart theme. Run from any working directory."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
t = json.loads((root / 'design/tokens.json').read_text())
css = ['/* Generated by scripts/generate_theme.py. */']
for mode in ('light', 'dark'):
    selector = ':root, [data-ng-theme="light"]' if mode == 'light' else '[data-ng-theme="dark"]'
    css.append(selector + ' {')
    css += [f'  --ng-{k}: {v};' for k, v in t[mode].items()]
    css += [f'  --ng-radius: {t["radius"]}px;', f'  --ng-height: {t["controlHeight"]}px;', f'  --ng-font-size: {t["fontSize"]}px;', '}']
css.append('[data-ng-density="compact"] { --ng-height: ' + str(t['compactControlHeight']) + 'px; }')
(root / 'src/NextgenComponents.Blazor/wwwroot/tokens.css').write_text('\n'.join(css) + '\n')
dart = ["// Generated by scripts/generate_theme.py.", "import 'package:flutter/material.dart';", "", 'abstract final class NgTokens {']
for k in ('radius', 'controlHeight', 'compactControlHeight', 'fontSize'):
    dart.append(f'  static const double {k} = {t[k]}.0;')
for mode in ('light', 'dark'):
    for key, value in t[mode].items():
        dart.append(f'  static const {mode}{key[0].upper() + key[1:]} = Color(0xff{value[1:]});')
dart.append('}')
(root / 'packages/nextgen_components/lib/src/tokens.dart').write_text('\n'.join(dart) + '\n')
